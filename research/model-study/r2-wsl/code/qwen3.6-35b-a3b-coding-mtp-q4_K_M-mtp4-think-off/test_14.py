def correct_bracketing(brackets: str):
    """ brackets is a string of "(" and ")".
    return True if every opening bracket has a corresponding closing bracket.

    >>> correct_bracketing("(")
    False
    >>> correct_bracketing("()")
    True
    >>> correct_bracketing("(()())")
    True
    >>> correct_bracketing(")(()")
    False
    """
    count = 0
    for char in brackets:
        if char == '(':
            count += 1
        elif char == ')':
            count -= 1
        # If count goes negative, we have a closing bracket without a matching opening one
        if count < 0:
            return False
    # If count is not zero, we have unmatched opening brackets
    return count == 0



