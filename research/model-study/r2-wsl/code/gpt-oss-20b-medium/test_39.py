from typing import Dict

def sort_numbers(numbers: str) -> str:
    """Input is a space-delimited string of numberals from 'zero' to 'nine'.
    Valid choices are 'zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight' and 'nine'.
    Return the string with numbers sorted from smallest to largest.
    >>> sort_numbers('three one five')
    'one three five'
    """
    # Mapping from word to numeric value
    word_to_value: Dict[str, int] = {
        'zero': 0,
        'one': 1,
        'two': 2,
        'three': 3,
        'four': 4,
        'five': 5,
        'six': 6,
        'seven': 7,
        'eight': 8,
        'nine': 9,
    }

    # Split input into words; handle empty string gracefully
    words = numbers.split()
    if not words:
        return ''

    # Sort words based on numeric value
    sorted_words = sorted(words, key=lambda w: word_to_value.get(w, 0))
    return ' '.join(sorted_words)



